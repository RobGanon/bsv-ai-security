# ---------------------------------------------------------------------------
# Synthetic chains under toy parameters
# ---------------------------------------------------------------------------

TOY = DAAParams(pow_limit_bits=0x20100000, target_spacing=600, daa_height=1147)
HISTORY_BITS = 0x1F100000  # target 2**244: work ~4096/block, self-consistent
BASE_TIME = 1_700_000_000
CHAIN_START = 1000
CHECKPOINT_HEIGHT = 1200
TIP_HEIGHT = 1300


def _compact(target: int) -> int:
    size = (target.bit_length() + 7) // 8
    if size <= 3:
        mantissa = target << (8 * (3 - size))
    else:
        mantissa = target >> (8 * (size - 3))
    if mantissa & 0x00800000:
        mantissa >>= 8
        size += 1
    return (size << 24) | mantissa


def _target(bits: int) -> int:
    size = bits >> 24
    word = bits & 0x007FFFFF
    if size <= 3:
        return word >> (8 * (3 - size))
    return word << (8 * (size - 3))


def _work(bits: int) -> int:
    t = _target(bits)
    return ((1 << 256) - 1 - t) // (t + 1) + 1


def _toy_expected_bits(chain: list[BlockHeader]) -> int:
    """Test-side DAA: bits for the next block after ``chain``.

    Times in the synthetic chains increase strictly, so the
    median-of-3 suitable block is always the middle of the three.
    """
    cum: list[int] = []
    acc = 0
    for h in chain:
        acc += _work(h.bits)
        cum.append(acc)
    last = len(chain) - 2  # suitable(prev) = middle of last three
    first = len(chain) - 2 - 144  # suitable(prev - 144)
    work = (cum[last] - cum[first]) * 600
    timespan = chain[last].time - chain[first].time
    timespan = min(max(timespan, 72 * 600), 288 * 600)
    work //= timespan
    target = ((1 << 256) - work) // work
    limit = _target(TOY.pow_limit_bits)
    return _compact(min(target, limit))


def _mine(prev: BlockHeader, height: int, time_: int, bits: int) -> BlockHeader:
    merkle = hashlib.sha256(f"synthetic-{height}".encode()).hexdigest()
    hdr = BlockHeader(
        version=1,
        prev_hash=prev.hash or "",
        merkle_root=merkle,
        time=time_,
        bits=bits,
        nonce=0,
        height=height,
    )
    target = _target(bits)
    while int(header_hash(hdr.to_bytes()), 16) > target:
        hdr = replace(hdr, nonce=hdr.nonce + 1)
    return replace(hdr, hash=header_hash(hdr.to_bytes()))


def _build_chain(bits_for) -> list[BlockHeader]:
    """Chain from CHAIN_START to TIP_HEIGHT. ``bits_for(chain, h)``
    picks each block's bits (history blocks use HISTORY_BITS)."""
    genesis = BlockHeader(
        version=1,
        prev_hash="00" * 32,
        merkle_root=hashlib.sha256(b"synthetic-base").hexdigest(),
        time=BASE_TIME,
        bits=HISTORY_BITS,
        nonce=0,
        height=CHAIN_START,
    )
    target = _target(HISTORY_BITS)
    while int(header_hash(genesis.to_bytes()), 16) > target:
        genesis = replace(genesis, nonce=genesis.nonce + 1)
    genesis = replace(genesis, hash=header_hash(genesis.to_bytes()))
    chain = [genesis]
    for h in range(CHAIN_START + 1, TIP_HEIGHT + 1):
        bits = bits_for(chain, h)
        chain.append(_mine(chain[-1], h, BASE_TIME + (h - CHAIN_START) * 600, bits))
    return chain


def _honest_bits(chain: list[BlockHeader], h: int) -> int:
    if h <= TOY.daa_height:
        return HISTORY_BITS
    return _toy_expected_bits(chain)


@pytest.fixture(scope="module")
def honest_chain() -> list[BlockHeader]:
    return _build_chain(_honest_bits)


def _verify(chain, daa=TOY, fetcher=None):
    by_height = {h.height: h for h in chain}
    checkpoint = by_height[CHECKPOINT_HEIGHT]
    tip = by_height[TIP_HEIGHT]
    return verify_chain_to_checkpoint(
        fetcher or FixtureFetcher(chain),
        tip_height=TIP_HEIGHT,
        tip_hash=tip.hash or "",
        checkpoint_hash=checkpoint.hash or "",
        checkpoint_height=CHECKPOINT_HEIGHT,
        daa=daa,
    )


def test_synthetic_honest_chain_verifies(honest_chain):
    ok, _checked, reason = _verify(honest_chain)
    assert ok, reason
    assert "difficulty schedule verified" in reason


def test_easy_bits_attack_rejected(honest_chain):
    def attack_bits(chain, h):
        if h <= CHECKPOINT_HEIGHT:
            return _honest_bits(chain, h)
        return TOY.pow_limit_bits  # declare the easiest legal bits

    chain = _build_chain(attack_bits)
    ok, _checked, reason = _verify(chain)
    assert not ok
    assert "difficulty schedule mismatch" in reason


def test_first_window_poisoning_rejected(honest_chain):
    # The v0.2 hole: poison the first blocks above the checkpoint
    # and let every later block honestly follow the poisoned
    # window. Induction from authenticated inputs must catch the
    # very first poisoned block.
    def poison_bits(chain, h):
        if h <= CHECKPOINT_HEIGHT:
            return _honest_bits(chain, h)
        if h == CHECKPOINT_HEIGHT + 1:
            return _compact(_target(_honest_bits(chain, h)) * 3 // 2)
        return _toy_expected_bits(chain)

    chain = _build_chain(poison_bits)
    ok, _checked, reason = _verify(chain)
    assert not ok
    assert "difficulty schedule mismatch" in reason
    assert str(CHECKPOINT_HEIGHT + 1) in reason


def test_bits_above_pow_limit_rejected(honest_chain):
    def limit_bits(chain, h):
        if h < TIP_HEIGHT:
            return _honest_bits(chain, h)
        return 0x20110000  # decodes above the toy pow-limit target

    chain = _build_chain(limit_bits)
    ok, _checked, reason = _verify(chain)
    assert not ok
    assert "bits out of range" in reason


def test_unfetchable_window_inputs_fail_closed(honest_chain):
    fetcher = FixtureFetcher(honest_chain, floor=CHECKPOINT_HEIGHT - 100)
    ok, _checked, reason = _verify(honest_chain, fetcher=fetcher)
    assert not ok
    assert "fetch failed" in reason


def test_default_mode_still_accepts_attack_chain():
    # Pins the boundary honestly: without a DAA parameter set the
    # walk remains linkage + PoW only (Finding B stays open for
    # chains whose parameters are unconfirmed, e.g. Teratestnet).
    def attack_bits(chain, h):
        if h <= CHECKPOINT_HEIGHT:
            return _honest_bits(chain, h)
        return TOY.pow_limit_bits

    chain = _build_chain(attack_bits)
    ok, _checked, _reason = _verify(chain, daa=None)
    assert ok


def test_header_chain_daa_mode(honest_chain):
    by_height = {h.height: h for h in honest_chain}
    heights = sorted(by_height)
    segment = [by_height[h] for h in heights if h >= 1250]
    inputs = [by_height[h] for h in heights if 1103 <= h < 1250]
    assert verify_header_chain(segment, daa=TOY, window_inputs=inputs)
    # Missing window inputs: fail closed.
    assert not verify_header_chain(segment, daa=TOY)
    # Missing heights: fail closed.
    stripped = [replace(h, height=None) for h in segment]
    assert not verify_header_chain(stripped, daa=TOY, window_inputs=inputs)
    # Default mode on the same segment is unchanged.
    assert verify_header_chain(segment)


def test_validate_daa_schedule_rejects_nonconsecutive():
    headers = _load_headers("mainnet_headers_recent.json")[:200]
    broken = headers[:100] + headers[101:]
    ok, reason = validate_daa_schedule(
        broken, DAAParams.mainnet(), first_vouched_height=broken[0].height or 0
    )
    assert not ok
    assert "not consecutive" in reason


def test_header_chain_verifier_passes_daa_through(honest_chain):
    by_height = {h.height: h for h in honest_chain}
    checkpoint = by_height[CHECKPOINT_HEIGHT]
    tip = by_height[TIP_HEIGHT]

    class TxFetcher(FixtureFetcher):
        def fetch_tx(self, txid: str) -> dict:
            return {"blockheight": TIP_HEIGHT, "blockhash": tip.hash}

    verifier = HeaderChainVerifier(
        TxFetcher(honest_chain),
        checkpoint_hash=checkpoint.hash or "",
        checkpoint_height=CHECKPOINT_HEIGHT,
        daa=TOY,
    )
    result = verifier.verify_chain_for_tx("ab" * 32)
    assert result.verified, result.reason
