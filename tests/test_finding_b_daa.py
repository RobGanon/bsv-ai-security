def test_golden_recent_window_verifies_with_schedule():
    headers = _load_headers("mainnet_headers_recent.json")
    checkpoint = headers[150]
    tip = headers[-1]
    ok, checked, reason = verify_chain_to_checkpoint(
        FixtureFetcher(headers),
        tip_height=tip.height,
        tip_hash=tip.hash,
        checkpoint_hash=checkpoint.hash,
        checkpoint_height=checkpoint.height,
        daa=DAAParams.mainnet(),
    )
    assert ok, reason
    assert "difficulty schedule verified" in reason
    assert checked == tip.height - checkpoint.height + 1


def test_golden_activation_window_verifies_with_schedule():
    # The fixture straddles the DAA activation: blocks below
    # 504032 are inputs only; every block from 504032 to the tip
    # must reproduce its real bits exactly.
    headers = _load_headers("mainnet_headers_daa_activation.json")
    by_height = {h.height: h for h in headers}
    checkpoint = by_height[503900]
    tip = headers[-1]
    assert tip.height > 504032
    ok, checked, reason = verify_chain_to_checkpoint(
        FixtureFetcher(headers),
        tip_height=tip.height,
        tip_hash=tip.hash,
        checkpoint_hash=checkpoint.hash,
        checkpoint_height=checkpoint.height,
        daa=DAAParams.mainnet(),
    )
    assert ok, reason
    assert "difficulty schedule verified" in reason


def test_validate_schedule_detects_tampered_real_header():
    # Schedule validation alone (no hash/PoW layer): bump one real
    # header's mantissa by one — a target no DAA would produce for
    # that window — and the schedule must reject it.
    headers = _load_headers("mainnet_headers_recent.json")
    segment = headers[4:304]
    # The first 147 headers are window inputs; vouching starts
    # only where a full window exists inside the segment.
    floor = segment[147].height or 0
    ok, reason = validate_daa_schedule(
        segment, DAAParams.mainnet(), first_vouched_height=floor
    )
    assert ok, reason
    idx = 200
    real = segment[idx]
    tampered = replace(real, bits=real.bits + 1)
    segment = segment[:idx] + [tampered] + segment[idx + 1:]
    ok, reason = validate_daa_schedule(
        segment,
        DAAParams.mainnet(),
        first_vouched_height=floor,
    )
    assert not ok
    assert "difficulty schedule mismatch" in reason


def test_golden_window_with_unfetchable_inputs_fails_closed():
    headers = _load_headers("mainnet_headers_recent.json")
    checkpoint = headers[150]
    tip = headers[-1]
    fetcher = FixtureFetcher(headers, floor=checkpoint.height - 100)
