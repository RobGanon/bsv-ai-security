"""Finding B: difficulty-schedule (cash DAA) validation.

Two kinds of evidence:

* Golden vectors — real mainnet headers fetched from
  WhatsOnChain (tests/fixtures/). The verifier must reproduce
  the real chain's bits exactly, across a recent window and
  across the DAA activation boundary (first DAA block 504032).
* Synthetic chains under toy parameters (huge pow limit, small
  heights) generated by an independent test-side implementation
  of the DAA: the honest chain verifies; the Finding B attacks
  (easy-bits extension, first-window poisoning) are rejected.

Toy parameters change only the constants (pow limit, activation
height) — the algorithm under test is the shipped one, the same
way the node tests its DAA under regtest parameters.
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import replace
from pathlib import Path

import pytest

from sealrun.spv import (
    BlockHeader,
    DAAParams,
    HeaderChainVerifier,
    SPVError,
    header_hash,
    validate_daa_schedule,
    verify_chain_to_checkpoint,
    verify_header_chain,
)

FIXTURES = Path(__file__).parent / "fixtures"


def _load_headers(name: str) -> list[BlockHeader]:
    rows = json.loads((FIXTURES / name).read_text())
    return [BlockHeader(**row) for row in rows]


class FixtureFetcher:
    """Serves fixture/synthetic headers by height."""

    def __init__(self, headers: list[BlockHeader], floor: int | None = None):
        self.by_height = {h.height: h for h in headers}
        self.floor = floor

    def fetch_header(self, height: int) -> BlockHeader:
        if self.floor is not None and height < self.floor:
            raise SPVError(f"no header below {self.floor}")
        try:
            return self.by_height[height]
        except KeyError:
            raise SPVError(f"no header at height {height}") from None

    def fetch_tx(self, txid: str) -> dict:
        raise SPVError("not used")


